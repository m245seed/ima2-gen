#!/usr/bin/env node
// Contract docs projection (070 WP7): render the tool catalog into the
// generated-marker section of skills/ima2/SKILL.md. Deterministic: same
// catalog -> same output. `--check` fails when the file is stale (CI gate).
import { readFileSync, writeFileSync } from "node:fs";

const START = "<!-- mcp-tools:generated:start -->";
const END = "<!-- mcp-tools:generated:end -->";
const SKILL_PATH = "skills/ima2/SKILL.md";

const { buildCatalog } = await import("../lib/contracts/catalog.ts");
const { catalogVersion, buildToolsList, executionBindingFor } = await import("../lib/contracts/discovery.ts");

const entries = buildCatalog({ snapshots: [] });
const version = catalogVersion(entries);
const rows = buildToolsList(entries);

const byNamespace = new Map();
for (const row of rows) {
  if (!byNamespace.has(row.namespace)) byNamespace.set(row.namespace, []);
  byNamespace.get(row.namespace).push(row);
}

let body = `${START}\n<!-- Generated by scripts/generate-contract-docs.mjs — do not edit by hand. -->\n\n`;
body += `### Machine tool contracts (catalog ${version.slice(0, 19)})\n\n`;
body += `Agents: run \`ima2 tools list --json\` for the live view; this section is the bundled-snapshot projection.\n\n`;
for (const [namespace, nsRows] of [...byNamespace.entries()].sort()) {
  body += `#### \`${namespace}\` (${nsRows.length})\n\n`;
  body += `| tool | executable via | description |\n|---|---|---|\n`;
  for (const row of nsRows.sort((a, b) => a.id.localeCompare(b.id))) {
    const entry = entries.find((e) => e.id === row.id);
    const binding = entry ? executionBindingFor(entry) : null;
    const via = namespace === "ima2" ? "agent runtime" : binding ? `\`${binding.endpoint}\`` : "—";
    body += `| \`${row.id}\` | ${via} | ${row.description.replaceAll("|", "\\|")} |\n`;
  }
  body += "\n";
}
body += END;

const current = readFileSync(SKILL_PATH, "utf8");
if (!current.includes(START) || !current.includes(END)) {
  console.error(`markers missing in ${SKILL_PATH}`);
  process.exit(2);
}
const next = current.slice(0, current.indexOf(START)) + body + current.slice(current.indexOf(END) + END.length);

if (process.argv.includes("--check")) {
  if (next !== current) { console.error("contract docs are stale — run: node scripts/generate-contract-docs.mjs"); process.exit(1); }
  console.log("contract docs up to date");
} else {
  writeFileSync(SKILL_PATH, next);
  console.log(`wrote generated section (${rows.length} tools) into ${SKILL_PATH}`);
}
