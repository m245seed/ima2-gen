import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import ts from "typescript";

const ROOT = resolve(import.meta.dirname, "..");
const SOURCE = resolve(ROOT, "lib/providers/registry.ts");
const TARGET = resolve(ROOT, "ui/src/generated/providers.ts");

async function loadRegistry() {
  const source = await readFile(SOURCE, "utf8");
  const output = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  const moduleUrl = `data:text/javascript;base64,${Buffer.from(output).toString("base64")}`;
  return (await import(moduleUrl)).REGISTRY;
}

function literal(value) {
  return JSON.stringify(value, null, 2);
}

function buildOutput(registry) {
  const providers = registry.map((provider) => provider.id);
  const models = registry.flatMap((provider) => provider.models.map((model) => ({
    ...model,
    provider: provider.id,
  })));
  const unique = (values) => [...new Set(values)];
  const imageModels = unique(models.filter((model) => model.kind === "image").map((model) => model.id));
  const supportedImages = unique(models.filter((model) => model.kind === "image" && Object.values(model.supports).some(Boolean)).map((model) => model.id));
  const unsupportedImages = imageModels.filter((id) => !supportedImages.includes(id));
  const referenceLimits = Object.fromEntries(registry.map((provider) => [provider.id, provider.referenceLimits]));
  return `// Generated by scripts/generate-provider-types.mjs. Do not edit.

export const CORE_PROVIDER_IDS = ${literal(providers)} as const;
export type CoreProviderId = typeof CORE_PROVIDER_IDS[number];
export const CORE_PROVIDER_ID_SET: ReadonlySet<string> = new Set(CORE_PROVIDER_IDS);
export function isCoreProviderId(value: unknown): value is CoreProviderId {
  return typeof value === "string" && CORE_PROVIDER_ID_SET.has(value);
}

export const IMAGE_MODEL_IDS = ${literal(supportedImages)} as const;
export type ImageModelId = typeof IMAGE_MODEL_IDS[number];
export const UNSUPPORTED_IMAGE_MODEL_IDS = ${literal(unsupportedImages)} as const;
export type UnsupportedImageModelId = typeof UNSUPPORTED_IMAGE_MODEL_IDS[number];
export const PROVIDER_REFERENCE_LIMITS = ${literal(referenceLimits)} as const;
`;
}

async function main() {
  const expected = buildOutput(await loadRegistry());
  if (process.argv.includes("--check")) {
    const current = await readFile(TARGET, "utf8").catch(() => "");
    if (current !== expected) {
      console.error("ui/src/generated/providers.ts is stale; run node scripts/generate-provider-types.mjs");
      process.exitCode = 1;
    }
    return;
  }
  await writeFile(TARGET, expected);
}

try {
  await main();
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
